import { expect, test } from '@playwright/test';

test('each test journey shows its own preparation and preserves custom input across switches', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Évaluer les modèles' }).click();
  const journeys = page.getByRole('group', { name: 'Parcours de test' });
  await page.getByRole('group', { name: 'Type d’évaluation' }).getByRole('button', { name: /Analyse seule/ }).click();
  const transcription = page.getByRole('textbox', { name: 'Transcription de référence pour l’évaluation de l’analyse' });
  await transcription.fill('Réponse personnelle conservée.');
  await journeys.getByRole('button', { name: /Schémas scientifiques/ }).click();
  await expect(page.getByRole('region', { name: 'Protocole schémas scientifiques', exact: true })).toBeVisible();
  await expect(page.locator('#evaluation-rubric')).toHaveCount(0);
  await expect(page.getByRole('navigation', { name: 'Espaces de l’évaluation' }).getByRole('button', { name: /Exécution/ })).toBeHidden();
  await page.screenshot({ path: 'test-results/evaluation-diagrams-desktop.png', fullPage: true });
  await expect(page.getByRole('group', { name: 'Type d’évaluation' })).toBeHidden();
  await expect(page.getByRole('region', { name: 'Lancer l’expérience' })).toHaveCount(0);
  await journeys.getByRole('button', { name: /Biologie/ }).click();
  await expect(page.getByRole('region', { name: 'Protocole de test guidé' })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Protocole schémas scientifiques', exact: true })).toBeHidden();
  await page.getByRole('button', { name: 'Vérifier la répétabilité', exact: true }).click();
  await page.getByLabel('Nombre de passages').selectOption('5');
  await page.getByRole('button', { name: 'Comparer les méthodes', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Test de répétabilité variante B' })).toBeHidden();
  await page.getByRole('button', { name: 'Vérifier la répétabilité', exact: true }).click();
  await expect(page.getByLabel('Nombre de passages')).toHaveValue('5');
  await page.screenshot({ path: 'test-results/evaluation-repeatability-desktop.png', fullPage: true });
  await page.getByRole('navigation', { name: 'Espaces de l’évaluation' }).getByRole('button', { name: /Campagnes de test/ }).click();
  await page.getByRole('navigation', { name: 'Espaces de l’évaluation' }).getByRole('button', { name: /Tests/ }).click();
  await expect(page.getByRole('button', { name: 'Vérifier la répétabilité', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await journeys.getByRole('button', { name: /Ma copie/ }).click();
  await expect(transcription).toHaveValue('Réponse personnelle conservée.');
  await expect(page.locator('#evaluation-rubric')).toBeVisible();
  await expect(page.getByRole('region', { name: 'Lancer l’expérience' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/evaluation-custom-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
});
