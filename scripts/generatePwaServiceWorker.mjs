import { createHash } from 'node:crypto';
import { access, readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';

// Cache only public application resources: never requests, copies, or API responses.
const root = resolve(process.argv[2] ?? 'dist');
const precache = ['', 'index.html', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png'];
async function listStaticAssets(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = [];
  for (const entry of entries) {
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) paths.push(...await listStaticAssets(fullPath));
    else if (entry.isFile() && /\.(?:js|mjs|css|woff2?|wasm|png|svg)$/.test(entry.name)) {
      paths.push(relative(root, fullPath).split(sep).join('/'));
    }
  }
  return paths;
}

precache.push(...(await listStaticAssets(join(root, 'assets'))).sort());
await Promise.all(precache.filter(Boolean).map(path => access(join(root, path))));
const revisionHash = createHash('sha256');
for (const path of precache.filter(Boolean)) {
  revisionHash.update(path);
  revisionHash.update(await readFile(join(root, path)));
}
const revision = revisionHash.digest('hex').slice(0, 16);
const source = `/* Generated by scripts/generatePwaServiceWorker.mjs. */
const CACHE_PREFIX = 'companion-correcteur-shell-';
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(revision)};
const APP_SCOPE = self.registration.scope;
const PRECACHE_URLS = ${JSON.stringify(precache)}.map(path => new URL(path, APP_SCOPE).href);
const PRECACHE_SET = new Set(PRECACHE_URLS);

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys
        .filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
        .map(key => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(APP_SCOPE)) return;

  if (request.mode === 'navigate') {
    // Network first: new deployments remain visible; offline navigation gets the shell.
    event.respondWith(
      fetch(request).catch(async () =>
        (await caches.match(new URL('index.html', APP_SCOPE).href)) || Response.error())
    );
    return;
  }

  // Explicit allowlist. In particular, don't intercept AI/API calls or user data.
  const resourceUrl = new URL(request.url);
  resourceUrl.search = '';
  if (!PRECACHE_SET.has(resourceUrl.href)) return;
  event.respondWith(
    caches.match(resourceUrl.href).then(cached => cached || fetch(request))
  );
});
`;
await writeFile(join(root, 'sw.js'), source, 'utf8');
console.log(`PWA shell: ${precache.length} assets, revision ${revision}`);
